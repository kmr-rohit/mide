#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.md: every crate that ends up in the mide app, with its license.

    python3 scripts/licenses.py            # rewrite THIRD_PARTY_LICENSES.md
    python3 scripts/licenses.py --check    # exit 1 if a dependency has a license outside the allow-list
"""
import json, os, shutil, subprocess, sys, collections, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARGO = shutil.which("cargo") or os.path.expanduser("~/.cargo/bin/cargo")
# Licenses we are happy to ship in an MIT-licensed app. Anything else needs a human look.
OK = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016",
      "MPL-2.0", "CC0-1.0", "Unlicense", "BSL-1.0", "0BSD", "OpenSSL", "LGPL-2.1-or-later", "NCSA"}

def main():
    meta = json.loads(subprocess.check_output(
        [CARGO, "metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-apple-darwin"],
        cwd=ROOT))
    # Only what the app binary depends on (not dev/build tooling of other crates).
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "mide")
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    pkgs = sorted((by_id[i] for i in seen if not by_id[i]["name"].startswith("mide")), key=lambda p: p["name"])

    groups = collections.defaultdict(list)
    for p in pkgs:
        groups[p["license"] or "UNKNOWN"].append(f'{p["name"]} {p["version"]}')

    def atoms(expr):  # "MIT OR Apache-2.0" -> {"MIT", "Apache-2.0"}
        return set(re.split(r"\s+(?:OR|AND|WITH)\s+|[()/ ]+", expr)) - {""}

    # An OR expression is fine if any one alternative is allowed.
    def acceptable(expr):
        if "UNKNOWN" == expr:
            return False
        return any(a in OK for a in atoms(expr))

    bad = {lic: names for lic, names in groups.items() if not acceptable(lic)}
    out = ["# Third-party licenses", "",
           "mide is MIT-licensed (see `LICENSE`). It is built from the open-source Rust crates below.",
           f"This list is generated by `scripts/licenses.py` ({len(pkgs)} crates).", ""]
    summary = collections.Counter()
    for lic, names in groups.items():
        summary[lic] += len(names)
    out += ["## Summary", "", "| License | Crates |", "|---|---|"]
    out += [f"| {lic} | {n} |" for lic, n in summary.most_common()]
    out += ["", "## Bundled data that is not a Rust crate", "",
            "* **Syntax grammars** (`.sublime-syntax`) come from the `syntect` and `two-face` crates: the default",
            "  set from the open-source [sublimehq/Packages](https://github.com/sublimehq/Packages) repository,",
            "  plus the extra grammars shipped with [bat](https://github.com/sharkdp/bat) (MIT / Apache-2.0).",
            "  Each grammar keeps its own permissive license; see those projects for the texts.",
            "* **Fonts**: none are bundled. mide uses Monaco, Menlo or any monospace font already on your Mac.",
            "* **App icon and website**: original to this project (MIT).",
            "* mide is an independent project and is not affiliated with Sublime HQ, Zed, GitHub or Anthropic.",
            "", "## Crates", ""]
    for lic, names in sorted(groups.items()):
        out += [f"### {lic}", "", ", ".join(names), ""]
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(out))
    print(f"{len(pkgs)} crates, {len(groups)} distinct license expressions")
    if bad:
        print("NEEDS REVIEW:")
        for lic, names in bad.items():
            print(f"  {lic}: {', '.join(names)}")
        if "--check" in sys.argv:
            sys.exit(1)
    else:
        print("all licenses are on the allow-list (no GPL/AGPL)")

main()
